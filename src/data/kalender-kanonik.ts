function buatItemKonsep(
  hari: DefinisiHariKalender,
  slot: SlotKonten,
  def: DefinisiSlotHarian,
): KonsepKonten {
  const adalahVideo = slot !== 'design';
  const distribusi =
    slot === 'video-a'
      ? DISTRIBUSI_VIDEO_A
      : slot === 'video-b'
        ? DISTRIBUSI_VIDEO_B
        : DISTRIBUSI_DESIGN;

  return {
    id: `${hari.tanggal}-${slot}`,
    hariKe: hari.hariKe,
    tanggal: hari.tanggal,
    labelTanggal: hari.labelTanggal,
    fase: hari.fase,
    slot,
    jenisMaster: adalahVideo ? 'video' : 'desain',
    judul: def.judul,
    hook: def.hook,
    ringkasan: def.ringkasan,
    pilar: def.pilar,
    tujuan: def.tujuan,
    distribusiKanal: distribusi,
    waktuUsulanUtama: WAKTU_UTAMA_SLOT[slot],
    materiBukti: def.materiBukti,
    drafCaption: def.drafCaption,
    cta: def.cta,
    status: 'planned',
    pic: def.pic,
    catatan: def.catatan,
    persetujuan: {
      status: 'belum-diajukan',
      disetujuiOleh: '',
      tanggalDisetujui: '',
      catatan: '',
    },
    asetTertaut: '',
    urlTerbit: '',
    tanggalTerbitAktual: '',
    adalahRencanaAwal: true,
  };
}

